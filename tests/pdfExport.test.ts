test('export flow - no pop-up, no tab navigation, no print() call', () => {
  // These are the three mechanisms that failed on iPhone: the pop-up was
  // blocked, the navigation discarded the test result, and print() did
  // nothing useful on a blob document.
  assert.ok(!/window\.open\(/.test(controlSource), 'no pop-up window is opened');
  assert.ok(!/window\.location\.assign/.test(controlSource), 'the tab is never navigated');
  assert.ok(!/location\.href\s*=/.test(controlSource), 'no location assignment');
  assert.ok(!/\.print\(\)/.test(controlSource), 'no reliance on window.print()');
});

test('export flow - the PDF is generated locally from the previewed data', () => {
  assert.match(controlSource, /buildPdf\(/, 'the PDF writer is used');
  assert.match(controlSource, /buildPrintReport\(data, origin \|\| undefined\)/, 'built from the previewed data model');
  assert.match(controlSource, /buildPdf\(\{ title: model\.title, lines: model\.lines \}\)/);
});

test('export flow - delivery prefers the share sheet and falls back to a download', () => {
  assert.match(controlSource, /nav\.canShare\(\{ files: \[file\] \}\)/, 'file sharing is attempted when supported');
  assert.match(controlSource, /a\.download = filename/, 'a real download anchor is the fallback');
  assert.match(controlSource, /pdfBlob\(bytes, model\.title\)/, 'a real PDF blob is produced');
});

test('export flow - the text fallback is offered only after a failure and is never called a PDF', () => {
  assert.match(controlSource, /The PDF could not be created on this device/, 'failure is stated plainly');
  assert.match(controlSource, /Download a plain-text \(\.txt\) report instead/);
  assert.match(controlSource, /The \.txt file is not a PDF/);
  // No button may promise a PDF while delivering text.
  assert.ok(
    !/>Download PDF report<\/[\s\S]{0,400}downloadTextReport\(\)/.test(controlSource),
    'the PDF button never triggers the text download'
  );
});

test('export flow - CSV stays a separate, independent download', () => {
  assert.match(controlSource, /Download CSV \(measurements\)/, 'CSV is its own action');
  assert.match(controlSource, /const downloadCsv = useCallback/, 'CSV generation is separate from the PDF path');
  assert.match(controlSource, /text\/csv/, 'CSV keeps its own MIME type');
});
